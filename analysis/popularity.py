"""Estimate how popular each number is among lottery players, from past winner counts.

Idea: the draw is uniform, so expected winners = tickets / C(45,6) for 1st prize no matter how people pick.
If a drawn combination had MORE winners than expected, players picked it more often than chance.
3rd prize (5 numbers matched) has thousands of winners per draw, so it gives a much less noisy signal than 1st.

Fits a negative-binomial GLM: log E[rank3 winners] = log(expected) + sum of per-number effects,
checks it on held-out draws (train on even rounds, evaluate odd rounds' 1st-prize sharing),
and writes src/lib/lotto/popularity-weights.ts for the app.

    python3 -m venv .venv && .venv/bin/pip install -r analysis/requirements.txt
    .venv/bin/python analysis/popularity.py
"""
import json, math, pathlib, urllib.request
import numpy as np, pandas as pd, statsmodels.api as sm

API = 'https://lotto.q-ova.com/api/draws'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'src/lib/lotto/popularity-weights.ts'
C = math.comb(45, 6)
RANK3_WAYS = 6 * 39  # combinations matching exactly 5 numbers and not the bonus

req = urllib.request.Request(API, headers={'User-Agent': 'lotto-note-analysis'})  # default urllib UA is blocked by Cloudflare
draws = sorted(json.load(urllib.request.urlopen(req)), key=lambda x: x['round'])
X = np.zeros((len(draws), 45))
w1, w3, e1, e3 = (np.zeros(len(draws)) for _ in range(4))
for i, d in enumerate(draws):
    X[i, [n - 1 for n in d['numbers']]] = 1
    tickets = d['totalSales'] / (2000 if d['round'] < 88 else 1000)  # price was 2,000 KRW before round 88
    w1[i], w3[i] = d['ranks'][0]['winners'], d['ranks'][2]['winners']
    e1[i], e3[i] = tickets / C, tickets * RANK3_WAYS / C

print(f'{len(draws)} draws. actual/expected winners: rank1 {w1.sum() / e1.sum():.3f}, rank3 {w3.sum() / e3.sum():.3f} (should be ~1)')

def fit(idx):
    model = sm.GLM(w3[idx], X[idx], family=sm.families.NegativeBinomial(alpha=0.05), offset=np.log(e3[idx]))
    params = model.fit_regularized(alpha=0.002, L1_wt=0.0).params
    return params - params.mean()

idx = np.arange(len(draws))
train, test = idx[idx % 2 == 0], idx[idx % 2 == 1]
score = X[test] @ fit(train)
quartile = pd.qcut(score, 4, labels=['lowest', 'low', 'high', 'highest'])
held = pd.DataFrame({'q': quartile, 'w1': w1[test], 'e1': e1[test]}).groupby('q', observed=True)
print('held-out 1st-prize sharing by predicted popularity (actual/expected):')
print(held.apply(lambda g: round(g.w1.sum() / g.e1.sum(), 3)).to_string())

weights = fit(idx)
lines = [
    '// Generated by analysis/popularity.py — do not edit by hand.',
    f'// Fitted on rounds 1-{draws[-1]["round"]}. Log-popularity per number (index 0 = number 1), centered at 0.',
    '// Positive = picked by more players than average, negative = fewer.',
    f'export const NUMBER_WEIGHTS: readonly number[] = {json.dumps([round(float(w), 4) for w in weights])};',
    f'export const FITTED_THROUGH_ROUND = {draws[-1]["round"]};',
    '',
]
OUT.write_text('\n'.join(lines))
print(f'wrote {OUT}')
